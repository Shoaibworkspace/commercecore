export const slugify = (name) =>
  name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
export const expandedProducts = expandedGroups.flatMap((group) =>
  group.rows.map((row, index) => {
    const [name, subject, rupees, color, dimensions] = row;
    const slug = slugify(name);
    const priceMinor = rupees * 100;
    const compareAtMinor =
      index % 3 === 2 ? null : (rupees + (rupees < 700 ? 200 : rupees < 1500 ? 400 : 700)) * 100;
    const sizes =
      name === 'Stacking Ring Trio' || name === 'Classic Signet Ring'
        ? ['6', '7', '8']
        : (group.sizes ?? ['Standard']);
    const image = `/images/photos/${slug}.webp`;
    return {
      id: `prod-${slug}`,
      slug,
      name,
      category: group.slug,
      subtitle:
        group.slug === 'clothing' ? 'Your everyday wardrobe, made easy.' : group.description,
      description: `${subject.charAt(0).toUpperCase()}${subject.slice(1).replace(/,? (?:neatly )?laid flat(?: together)?|, no logo|, no branding|, photographed alone/g, '')}. ${group.slug === 'clothing' ? 'An easy addition to your everyday wardrobe. Choose your size above.' : group.slug === 'footwear' ? 'A comfortable-looking pair for everyday plans. Choose your usual UK size.' : group.slug === 'jewellery' ? 'A simple finishing touch for everyday outfits. Fashion jewellery; no precious-metal certification.' : group.slug === 'electronics' ? 'Useful tech for everyday routines. Compatibility and technical specifications are illustrative.' : 'A thoughtful addition to your everyday essentials.'}`,
      material:
        group.slug === 'clothing'
          ? /linen/i.test(subject)
            ? 'Linen-blend fabric; demo composition.'
            : /denim/i.test(subject)
              ? 'Cotton denim; demo composition.'
              : /athletic/i.test(subject)
                ? 'Stretch performance fabric; demo composition.'
                : /knit|fleece/i.test(subject)
                  ? 'Soft blended knit fabric; demo composition.'
                  : 'Cotton-rich fabric; demo composition.'
          : group.material,
      dimensions:
        dimensions ??
        (group.slug === 'clothing'
          ? 'Sizes S, M, L and XL; choose your usual fit. Demo sizing.'
          : 'UK sizes 5–9; choose your usual fit. Demo sizing.'),
      care: group.care,
      featured: index === 0,
      isNew: index < 3,
      variants: sizes.map((size, position) => ({
        id: `var-${slug}-${position}`,
        label: size === 'Standard' ? 'Standard' : size,
        size: size === 'Standard' ? '' : size,
        color,
        priceMinor,
        compareAtMinor,
        stock: 10 + ((index * 3 + position) % 19),
        image,
        detailImage: image,
      })),
      gallery: [{ image, alt: `${name}, studio product photograph` }],
      photoSubject: subject,
    };
  }),
);
if (expandedProducts.length !== 88)
  throw new Error(`Expected 88 new products, got ${expandedProducts.length}`);

